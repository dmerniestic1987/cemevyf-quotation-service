import { Injectable, Logger, OnModuleInit, Optional } from '@nestjs/common';
import { randomUUID } from 'crypto';
import { createReadStream } from 'fs';
import { access, mkdir, unlink, writeFile } from 'fs/promises';
import { isAbsolute, join, resolve } from 'path';
import { Readable } from 'stream';
import { files as filesConfig } from 'config';
import { notFoundError } from '../errors/exceptions';
import { FileStorage } from './file-storage';

const STORED_FILE_NAME_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(png|jpg|pdf)$/;

@Injectable()
export class LocalDiskFileStorageService implements FileStorage, OnModuleInit {
  private readonly logger = new Logger(LocalDiskFileStorageService.name);
  private readonly uploadDir: string;

  constructor(@Optional() uploadDir: string = filesConfig.uploadDir) {
    this.uploadDir = isAbsolute(uploadDir) ? uploadDir : resolve(process.cwd(), uploadDir);
  }

  async onModuleInit(): Promise<void> {
    await mkdir(this.uploadDir, { recursive: true, mode: 0o700 });
  }

  async save(content: Buffer, extension: string): Promise<string> {
    const storedFileName = `${randomUUID()}${extension}`;
    const path = this.resolvePath(storedFileName);
    // "wx" never overwrites an existing file; the permissions keep the medical data private to the service user
    await writeFile(path, content, { flag: 'wx', mode: 0o600 });
    return storedFileName;
  }

  async createReadStream(storedFileName: string): Promise<Readable> {
    const path = this.resolvePath(storedFileName);
    try {
      await access(path);
    } catch {
      this.logger.error(`Stored file ${storedFileName} is missing on disk`);
      throw notFoundError('File not found');
    }
    return createReadStream(path);
  }

  async delete(storedFileName: string): Promise<void> {
    const path = this.resolvePath(storedFileName);
    try {
      await unlink(path);
    } catch (error) {
      if (error.code !== 'ENOENT') {
        throw error;
      }
    }
  }

  /**
   * Resolves the absolute path of a stored file. The name must match the exact format generated by this service
   * (uuid + known extension), so a tampered value such as "../../etc/passwd" can never escape the upload directory.
   */
  private resolvePath(storedFileName: string): string {
    if (!STORED_FILE_NAME_REGEX.test(storedFileName)) {
      throw new Error(`Invalid stored file name: ${storedFileName}`);
    }
    return join(this.uploadDir, storedFileName);
  }
}
